const DICT: Record<Lang, Translations> = { en, 'zh-TW': zhTW, 'zh-CN': zhCN, ja }

// Key lookup — handles both plain strings and functions
type TKey = keyof Translations
type TValue<K extends TKey> = Translations[K]

export function translate(lang: Lang, key: TKey): TValue<typeof key> {
  return (DICT[lang]?.[key] ?? DICT['en'][key]) as TValue<typeof key>
}

